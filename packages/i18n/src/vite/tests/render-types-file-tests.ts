import { readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { renderTypesFile } from "../utils/helpers/render-types-file";
import type { ScanResult } from "../utils/helpers/scan-namespaces";
import { writeIfChanged } from "../utils/helpers/write-if-changed";
import { createFixtureTree } from "./helpers";

const contents: Record<string, Record<string, unknown>> = {
  "common/es": { save: "Guardar", actions: { cancel: "Cancelar" }, "sign-in.title": "Entrar" },
  "auth/es": {
    welcome: "Hola, {{name}}",
    quote: 'Dice "hola"\n',
    login: { title: "Entrar" },
    list: ["uno", 2, true, null],
  },
  "auth/en": { welcome: "Hi, {{name}}" },
};

const scan: ScanResult = {
  languages: ["en", "es"],
  namespaces: [
    { name: "auth", dir: "src/features/auth/locales", files: { en: "auth/en", es: "auth/es" } },
    { name: "common", dir: "src/common/locales", files: { es: "common/es" } },
    { name: "empty", dir: "src/features/empty/locales", files: { en: "empty/en" } },
  ],
};
const contentOf = (file: string) => contents[file];

const expected = `// Generated by @aureus-core/i18n from the "es" locale files. Do not edit it by hand:
// it is rewritten whenever they change. Commit it, so type checks work without starting Vite.
import "i18next";

declare module "i18next" {
  interface ResourceNamespaceMap {
    auth: {
      list: readonly ["uno", 2, true, null];
      login: {
        title: "Entrar";
      };
      quote: "Dice \\"hola\\"\\n";
      welcome: "Hola, {{name}}";
    };
    common: {
      actions: {
        cancel: "Cancelar";
      };
      save: "Guardar";
      "sign-in.title": "Entrar";
    };
    empty: {};
  }

  interface CustomTypeOptions {
    defaultNS: "common";
  }
}
`;

describe("renderTypesFile", () => {
  it("renders the typesFrom content as literal types, sorted, quoting names only when needed", () => {
    expect(renderTypesFile(scan, { typesFrom: "es", defaultNamespace: "common" }, contentOf)).toBe(
      expected,
    );
  });

  it("omits CustomTypeOptions without a default namespace", () => {
    const output = renderTypesFile(scan, { typesFrom: "es" }, contentOf);
    expect(output).not.toContain("CustomTypeOptions");
    expect(output).toContain("interface ResourceNamespaceMap");
  });

  it("is byte-identical for the same input", () => {
    const options = { typesFrom: "es", defaultNamespace: "common" };
    expect(renderTypesFile(scan, options, contentOf)).toBe(
      renderTypesFile(scan, options, contentOf),
    );
  });
});

describe("writeIfChanged", () => {
  const cleanups: Array<() => void> = [];
  afterEach(() => {
    for (const remove of cleanups.splice(0)) remove();
  });

  it("creates the folder, writes, and does not rewrite unchanged content", () => {
    const tree = createFixtureTree({});
    cleanups.push(tree.remove);
    const file = join(tree.root, "src/types/i18next.d.ts");

    expect(writeIfChanged(file, "a")).toBe(true);
    expect(readFileSync(file, "utf8")).toBe("a");
    const { mtimeMs } = statSync(file);

    expect(writeIfChanged(file, "a")).toBe(false);
    expect(statSync(file).mtimeMs).toBe(mtimeMs);

    expect(writeIfChanged(file, "b")).toBe(true);
    expect(readFileSync(file, "utf8")).toBe("b");
  });
});
