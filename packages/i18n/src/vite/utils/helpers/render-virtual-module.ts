import { HMR_UPDATE_EVENT } from "@/internal/utils/constants";
import { toPosixPath } from "./match-glob";
import type { ScanResult } from "./scan-namespaces";

export interface RenderVirtualModuleOptions {
  readonly defaultNamespace?: string | undefined;
  /** Adds the `import.meta.hot` listener that feeds `onUpdate`. Development only. */
  readonly dev: boolean;
}

/**
 * The code of `virtual:aureus-i18n`: the discovered languages and namespaces, and one lazy
 * `import()` per locale file. Static paths let the bundler emit one chunk per file, loaded only
 * when the runtime asks for that language and namespace.
 */
export function renderVirtualModule(scan: ScanResult, options: RenderVirtualModuleOptions): string {
  const loaders = scan.namespaces.flatMap((namespace) =>
    Object.entries(namespace.files).map(
      ([language, file]) =>
        `  ${JSON.stringify(`${language}/${namespace.name}`)}: () => import(${JSON.stringify(toPosixPath(file))}),`,
    ),
  );
  const fields = [
    `  languages: ${JSON.stringify(scan.languages)},`,
    `  namespaces: ${JSON.stringify(scan.namespaces.map((namespace) => namespace.name))},`,
  ];
  if (options.defaultNamespace !== undefined) {
    fields.push(`  defaultNamespace: ${JSON.stringify(options.defaultNamespace)},`);
  }
  const lines = [
    "// Generated by @aureus-core/i18n.",
    "const loaders = {",
    ...loaders,
    "};",
    "const listeners = new Set();",
    "export default {",
    ...fields,
    "  load(language, namespace) {",
    '    const key = language + "/" + namespace;',
    "    if (!Object.hasOwn(loaders, key)) return Promise.resolve({});",
    "    return loaders[key]().then((module) => module.default);",
    "  },",
    "  onUpdate(listener) {",
    "    listeners.add(listener);",
    "    return () => {",
    "      listeners.delete(listener);",
    "    };",
    "  },",
    "};",
  ];
  if (options.dev) {
    lines.push(
      "if (import.meta.hot) {",
      `  import.meta.hot.on(${JSON.stringify(HMR_UPDATE_EVENT)}, (update) => {`,
      "    for (const listener of listeners) listener(update);",
      "  });",
      "}",
    );
  }
  lines.push("");
  return lines.join("\n");
}
