import type { I18nResourceContent } from "@/internal/types";
import type { ScanResult } from "./scan-namespaces";

/** The default `typesFile` of the plugin. */
export const DEFAULT_TYPES_FILE = "src/types/i18next.d.ts";

/** Two spaces per nesting level. */
const indentOf = (depth: number) => "  ".repeat(depth);

/** Names that can be written without quotes. ASCII only: any other name is quoted. */
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A property name, quoted only when needed: the way Biome and Prettier format it by default. */
const propertyName = (key: string) => (IDENTIFIER.test(key) ? key : JSON.stringify(key));

/** A JSON value as a TypeScript literal type: strings stay literal, so interpolation is typed. */
function renderType(value: unknown, depth: number): string {
  if (typeof value === "string" || typeof value === "number" || typeof value === "boolean") {
    return JSON.stringify(value);
  }
  if (value === null) return "null";
  if (Array.isArray(value)) {
    return `readonly [${value.map((item) => renderType(item, depth)).join(", ")}]`;
  }
  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).sort(([a], [b]) =>
      a < b ? -1 : a > b ? 1 : 0,
    );
    if (entries.length === 0) return "{}";
    const lines = entries.map(
      ([key, item]) =>
        `${indentOf(depth + 1)}${propertyName(key)}: ${renderType(item, depth + 1)};`,
    );
    return `{\n${lines.join("\n")}\n${indentOf(depth)}}`;
  }
  return "unknown";
}

/** Options of `renderTypesFile`. */
export interface RenderTypesOptions {
  /** The language the types are generated from. */
  readonly typesFrom: string;
  /** Declared as i18next's `defaultNS`; omitted when there is none. */
  readonly defaultNamespace?: string | undefined;
}

/**
 * The declaration file that types i18next from the `typesFrom` files: each namespace goes into
 * `ResourceNamespaceMap` (merged by i18next with other augmentations), and `defaultNamespace`, if
 * any, into `CustomTypeOptions.defaultNS`. The output is deterministic: namespaces and keys are
 * sorted. A namespace without a readable `typesFrom` file has no keys.
 */
export function renderTypesFile(
  scan: ScanResult,
  options: RenderTypesOptions,
  contentOf: (file: string) => I18nResourceContent | undefined,
): string {
  const namespaces = scan.namespaces.map((namespace) => {
    const file = namespace.files[options.typesFrom];
    const content = (file ? contentOf(file) : undefined) ?? {};
    return `    ${propertyName(namespace.name)}: ${renderType(content, 2)};`;
  });
  const lines = [
    `// Generated by @aureus-core/i18n from the "${options.typesFrom}" locale files. Do not edit it by hand:`,
    "// it is rewritten whenever they change. Commit it, so type checks work without starting Vite.",
    'import "i18next";',
    "",
    'declare module "i18next" {',
    "  interface ResourceNamespaceMap {",
    ...namespaces,
    "  }",
  ];
  if (options.defaultNamespace !== undefined) {
    lines.push(
      "",
      "  interface CustomTypeOptions {",
      `    defaultNS: ${JSON.stringify(options.defaultNamespace)};`,
      "  }",
    );
  }
  lines.push("}", "");
  return lines.join("\n");
}
