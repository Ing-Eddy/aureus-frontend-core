import { typographyVariants } from "@aureus-core/ui/components/typography";
import { defaultTypographyName } from "./default-typography";
import { formatNumber, formatSize } from "./fluid-size";
import { fontPackages, installCommand, unverifiedPackages } from "./install-command";
import { fontRoles, type ResolvedTypography, type VariantStyle } from "./typography-types";

/** The six declarations of one variant, as `typography.css` writes them. */
export function variantDeclarations(variant: string, style: VariantStyle): string[] {
  const name = `--typography-${variant}`;
  return [
    `${name}-font: var(--typography-font-${style.font});`,
    `${name}-size: ${formatSize(style.size)};`,
    `${name}-line-height: ${style.lineHeight === "inherit" ? "inherit" : formatNumber(style.lineHeight)};`,
    `${name}-weight: ${Math.round(style.weight)};`,
    `${name}-tracking: ${formatNumber(style.tracking)}em;`,
    `${name}-transform: ${style.transform};`,
  ];
}

/** Every declaration, in the package's order: roles, tracking, then each variant in catalog order. */
export function typographyDeclarations(typography: ResolvedTypography): string[] {
  return [
    ...fontRoles.map((role) => `--typography-font-${role}: ${typography.fonts[role].stack};`),
    `--typography-tracking-normal: ${formatNumber(typography.tracking)}em;`,
    ...typographyVariants.flatMap((variant) =>
      variantDeclarations(variant, typography.variants[variant]),
    ),
  ];
}

/** The `:root` block, shared by the export and the live preview. */
export function typographyVariableBlock(typography: ResolvedTypography): string {
  return `:root {\n${typographyDeclarations(typography)
    .map((line) => `  ${line}`)
    .join("\n")}\n}`;
}

const safeComment = (text: string) => text.replace(/\*\//g, "* /");

/** The app file (design D5). Deterministic: the same typography gives the same bytes. */
export function serializeTypography(typography: ResolvedTypography): string {
  const name = safeComment(typography.name.trim() || defaultTypographyName);
  const install = installCommand(typography);
  const unverified = unverifiedPackages(typography);
  const header = [
    `/* ${name} — Aureus typography. Generated by Aureus Typography Builder.`,
    install
      ? `   Install: ${install}`
      : "   No font install needed: the fonts bundled with @aureus-core/ui are used.",
    ...(unverified.length
      ? [`   Unverified packages (custom fonts, check they exist): ${unverified.join(", ")}`]
      : []),
    "   Import this file after @aureus-core/ui/styles.css. */",
  ].join("\n");
  const imports = fontPackages(typography).map((name) => `@import "${name}";`);
  return `${[header, ...(imports.length ? [imports.join("\n")] : []), typographyVariableBlock(typography)].join("\n\n")}\n`;
}
